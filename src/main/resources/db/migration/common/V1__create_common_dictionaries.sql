-- Служебная таблица зарегистрированных справочников.
CREATE TABLE common_dictionaries
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(255) NOT NULL,
    name         VARCHAR(255) NOT NULL,
    entity_class VARCHAR(255) NOT NULL,
    dto_class    VARCHAR(500) NOT NULL,
    generated_at TIMESTAMP NOT NULL,

    CONSTRAINT uk_common_dictionaries_code
        UNIQUE (code),

    CONSTRAINT uk_common_dictionaries_entity_class
        UNIQUE (entity_class)
);